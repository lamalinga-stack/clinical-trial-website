let currentLanguage = 'en';

function t(key) {
  return translations[currentLanguage]?.[key] || translations['en'][key] || key;
}

function setLanguage(lang) {
  currentLanguage = lang;
  localStorage.setItem('language', lang);
  updatePageLanguage();
}

function getCountryName(countryId) {
  return t(countryId) || countryId;
}

function populateCountrySelect() {
  const select = document.querySelector('#country-select');
  if (!select) return;

  // Keep the "All countries" option
  const allCountriesOption = select.querySelector('[value=""]');
  const existingOptions = select.querySelectorAll('option:not([value=""])');
  existingOptions.forEach((opt) => opt.remove());

  // Add translated country options
  countries.forEach((country) => {
    const option = document.createElement('option');
    option.value = country.value;
    option.textContent = getCountryName(country.id);
    option.dataset.countryId = country.id;
    select.appendChild(option);
  });
}

function updatePageLanguage() {
  // Update all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    el.textContent = t(key);
  });

  // Update all input placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    el.placeholder = t(key);
  });

  // Update country dropdown
  populateCountrySelect();

  // Update language selector
  const langButtons = document.querySelectorAll('.lang-btn');
  langButtons.forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.lang === currentLanguage);
  });

  // Re-render search results if they exist
  if (window.searchTrials) {
    window.searchTrials();
  }
}

// Initialize language on page load
window.addEventListener('DOMContentLoaded', () => {
  const savedLanguage = localStorage.getItem('language') || 'en';
  currentLanguage = savedLanguage;
  updatePageLanguage();
});
